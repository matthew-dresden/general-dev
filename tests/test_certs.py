# ---------------------------------------------------------------------------
# code_review round 3, BLOCKING A: a pre-existing ca.pem with no matching
# ca-key.pem must survive create_ca's failure UNCHANGED, not merely "still
# present". The pre-flight check used to test only `paths.ca_key.exists()`,
# so a lone stale `ca.pem` sailed past it; `create_ca` then created a fresh
# `ca-key.pem` inside the try block, hit `_prepare_output_file`'s
# `FileExistsError` on the pre-existing `ca.pem`, and the except handler's
# unconditional `paths.ca_cert.unlink(missing_ok=True)` deleted that
# pre-existing `ca.pem` -- exactly the "partially written" material the
# except handler's own docstring claims to scope to, but this file was never
# written by this invocation at all. Asserting mere existence (round 2's
# version of this test) cannot catch a delete-then-nothing-recreated-it
# defect the way asserting the original content survives can. The symmetric
# case (a lone stale `ca-key.pem` with no matching `ca.pem`) is covered by
# the sibling test directly below.
# ---------------------------------------------------------------------------


def test_create_ca_leaves_no_partial_material_when_ca_cert_preexists(tmp_path: Path) -> None:
    certs = _import_certs()
    paths = certs.CertPaths(instance=f"partial-ca-{uuid.uuid4().hex[:8]}", root=tmp_path)
    paths.ca_dir.mkdir(parents=True)
    stale_ca_cert = "stale ca.pem with no matching ca-key.pem"
    paths.ca_cert.write_text(stale_ca_cert, encoding="ascii")

    with pytest.raises(certs.CertsError, match="already exists"):
        certs.create_ca(paths)

    assert not paths.ca_key.exists()
    assert paths.ca_cert.read_text(encoding="ascii") == stale_ca_cert


def test_create_ca_leaves_no_partial_material_when_ca_key_preexists(tmp_path: Path) -> None:
    certs = _import_certs()
    paths = certs.CertPaths(instance=f"partial-ca-{uuid.uuid4().hex[:8]}", root=tmp_path)
    paths.ca_dir.mkdir(parents=True)

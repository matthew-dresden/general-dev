"""Tests for devcontainer_config.certs (spec Section 4.5; E6-F1-S1-T1).

The `devcontainer_config.certs` import is deferred into function bodies (via
`_import_certs`) instead of done once at module scope, for the same reason
`tests/test_repo.py` and `tests/test_hostprobe.py` document: the TDD RED gate
stashes this unit's own production-source files -- `certs.py` is new, added
by this task -- and re-runs a single named test node. A module-level `from
devcontainer_config.certs import ...` would fail COLLECTION for the whole
file (pytest exit code 2, no test outcome recorded) instead of failing the
one named test for the real reason: the module is missing. `_certs_module_path`
reads the file by path rather than importing it, for the identical reason.

Every certificate this file inspects is generated by the module under test,
into a fresh directory under `tmp_path`, and inspected by shelling out to the
real `openssl x509 -noout -text` (SANs, extended key usage) or `-startdate
-enddate` (lifetimes) -- never by re-reading the arguments this module
passed to its own `openssl` calls, which is what makes the SAN and
`clientAuth`/`serverAuth` assertions genuine parses of generated material
(AC-5.2, AC-TEST-001, AC-TEST-002) rather than a test that could pass even if
the generated certificate were wrong.

`issued_material` is a module-scoped fixture: one CA, one server certificate
and one client certificate, issued once into a `tmp_path_factory` directory
and reused by every read-only assertion below (SANs, key usage, modes,
default lifetimes, the "CA already exists" error, and the no-network and
no-stray-file checks). Tests that need a *different* environment --
`CERT_CLIENT_DAYS` overridden, `openssl` missing, no CA created yet -- build
their own fresh `CertPaths` under a function-scoped `tmp_path` instead of
sharing this fixture, since mutating shared state there would make one
test's outcome depend on another's execution order.
"""


# AC-TEST-001 / AC-TEST-002: SANs and extended key usage, parsed for real.
# ---------------------------------------------------------------------------


def test_server_certificate_has_required_sans_and_no_others(
    issued_material: _IssuedMaterial, tmp_path: Path
) -> None:
    text = _openssl_text_from_pem(issued_material.server.cert_pem, tmp_path, "server-cert.pem")
    san_line = next(line for line in text.splitlines() if "Subject Alternative Name" in line)
    san_values_line = text.splitlines()[text.splitlines().index(san_line) + 1].strip()
    assert san_values_line == "IP Address:127.0.0.1, DNS:localhost"


@pytest.mark.parametrize(
    "expected_usage,role",
    [("TLS Web Server Authentication", "server"), ("TLS Web Client Authentication", "client")],
)
def test_extended_key_usage_matches_role(
    issued_material: _IssuedMaterial, tmp_path: Path, expected_usage: str, role: str
) -> None:
    if role == "server":
        text = _openssl_text_from_pem(issued_material.server.cert_pem, tmp_path, "server-cert.pem")
    else:
        text = _openssl_text(issued_material.paths.client_cert)
    assert expected_usage in text



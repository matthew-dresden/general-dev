#!/usr/bin/env node
// generate-agents.mjs - derives opencode agents from a single source of truth.
//
// Source of truth:
//   opencode.json           - provider ids, model ids, subagent_depth (the
//                             INSTALLED config: the postcreate jq-rewrite of
//                             the shipped .devcontainer/opencode.json, with
//                             enabled_providers and the model matrix resolved)
//   lib/agents.inputs.json  - providers/roles to cover, optional concurrency caps
//
// This is the container copy. It is never run in place: the postcreate copies
// lib/ (this file and agents.inputs.json) into ~/.config/opencode/lib/ and
// runs it there, so ROOT below resolves to the installed config's directory
// and the outputs land in ~/.config/opencode/agent and lib.
//
// Outputs:
//   agent/<name>.md           - role agents (build/plan) and per-provider workers
//   lib/generated-agents.json - deterministic manifest consumed by tests/validation
//
// Standards (AGENTS.md): fail-fast (no fallbacks, no silent defaults), input-driven
// (no hardcoded provider/model/depth values), DRY (one template per role), 12-factor
// (derived artifacts are regenerated per machine; deterministic output, no timestamps).
//
// Disclosed static surface (code, not config): the three role semantics below and
// opencode's permission-key vocabulary. Everything else is derived from inputs.
//
// Usage:
//   node lib/generate-agents.mjs             write agent files + manifest
//   node lib/generate-agents.mjs --dry-run   print the plan, write nothing
//   node lib/generate-agents.mjs --check     exit 0 if generated files are in sync,
//                                            exit 1 with a drift list otherwise
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const CONFIG_PATH = join(ROOT, "opencode.json")
const INPUTS_PATH = join(ROOT, "lib", "agents.inputs.json")
const MANIFEST_PATH = join(ROOT, "lib", "generated-agents.json")
const AGENT_DIR = join(ROOT, "agent")
const MANIFEST_SCHEMA = 1

const MARKER =
  "<!-- GENERATED by lib/generate-agents.mjs - DO NOT EDIT. " +
  "Source: opencode.json + lib/agents.inputs.json. Regenerate with: /generate-agents -->"

// ---------------------------------------------------------------- strict JSONC

// Minimal, strict JSONC comment stripper. Tracks string state so "//" inside
// strings survives. No repair, no fallback: malformed input throws.
function stripJsonComments(text, label) {
  let out = ""
  let inString = false
  let escaped = false
  let inLine = false
  let inBlock = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    const next = i + 1 < text.length ? text[i + 1] : ""
    if (inLine) {
      if (c === "\n") {
        inLine = false
        out += c
      }
      continue
    }
    if (inBlock) {
      if (c === "*" && next === "/") {
        inBlock = false
        i++
      }
      continue
    }
    if (inString) {
      out += c
      if (escaped) escaped = false
      else if (c === "\\") escaped = true
      else if (c === '"') inString = false
      continue
    }
    if (c === "/" && next === "/") {
      inLine = true
      i++
      continue
    }
    if (c === "/" && next === "*") {
      inBlock = true
      i++
      continue
    }
    if (c === '"') inString = true
    out += c
  }
  if (inString || inBlock || inLine) {
    throw new Error(`${label}: malformed JSONC - unterminated string or comment at EOF`)
  }
  return out
}

function parseJsonc(text, label) {
  let parsed
  try {
    parsed = JSON.parse(stripJsonComments(text, label))
  } catch (err) {
    throw new Error(`${label}: invalid JSONC: ${err.message}`)
  }
  return parsed
}

// ------------------------------------------------------------------ validation

function fail(msg) {
  throw new Error(`generate-agents: ${msg}`)
}

function requireObject(value, label) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    fail(`${label} must be an object`)
  }
  return value
}

function readInputs() {
  const raw = parseJsonc(readFileSync(INPUTS_PATH, "utf-8"), INPUTS_PATH)
  const inputs = requireObject(raw, "inputs")
  if (!Array.isArray(inputs.providers) || inputs.providers.length === 0) {
    fail("inputs.providers must be a non-empty array of provider ids")
  }
  for (const p of inputs.providers) {
    if (typeof p !== "string" || p.length === 0) fail("inputs.providers entries must be non-empty strings")
  }
  if (new Set(inputs.providers).size !== inputs.providers.length) fail("inputs.providers must not contain duplicates")
  const VALID_ROLES = ["build", "plan"]
  if (!Array.isArray(inputs.roles) || inputs.roles.length === 0) {
    fail("inputs.roles must be a non-empty array")
  }
  for (const r of inputs.roles) {
    if (!VALID_ROLES.includes(r)) fail(`inputs.roles: unknown role "${r}" (valid: ${VALID_ROLES.join(", ")})`)
  }
  if (new Set(inputs.roles).size !== inputs.roles.length) fail("inputs.roles must not contain duplicates")
  const concurrency = requireObject(inputs.concurrency ?? {}, "inputs.concurrency")
  for (const [key, value] of Object.entries(concurrency)) {
    if (!inputs.providers.includes(key)) fail(`inputs.concurrency key "${key}" is not a listed provider`)
    if (!Number.isInteger(value) || value < 1) fail(`inputs.concurrency["${key}"] must be a positive integer`)
  }
  // Model selection: which configured models get agents. Explicit per provider
  // (no defaults); every entry is validated against opencode.jsonc in readConfig.
  const models = requireObject(inputs.models ?? null, "inputs.models")
  for (const p of inputs.providers) {
    const list = models[p]
    if (!Array.isArray(list) || list.length === 0) fail(`inputs.models["${p}"] must be a non-empty array of model ids`)
    if (new Set(list).size !== list.length) fail(`inputs.models["${p}"] must not contain duplicates`)
    for (const m of list) {
      if (typeof m !== "string" || m.length === 0) fail(`inputs.models["${p}"] entries must be non-empty strings`)
    }
  }
  for (const key of Object.keys(models)) {
    if (!inputs.providers.includes(key)) fail(`inputs.models key "${key}" is not a listed provider`)
  }
  return { providers: inputs.providers, roles: inputs.roles, models, concurrency }
}

function readConfig(inputs) {
  const config = requireObject(parseJsonc(readFileSync(CONFIG_PATH, "utf-8"), CONFIG_PATH), "config")
  const depth = config.subagent_depth
  if (!Number.isInteger(depth) || depth < 1) fail("config.subagent_depth must be an integer >= 1")
  const providerCfg = requireObject(config.provider, "config.provider")
  const providers = {}
  for (const id of inputs.providers) {
    const block = requireObject(providerCfg[id], `config.provider["${id}"] (is it defined in opencode.jsonc?)`)
    const configured = requireObject(block.models ?? null, `config.provider["${id}"].models (add models to opencode.jsonc)`)
    for (const m of inputs.models[id]) {
      if (!(m in configured)) {
        fail(`inputs.models["${id}"] lists model "${m}" which is not defined in config.provider["${id}"].models`)
      }
    }
    providers[id] = { modelIds: inputs.models[id] }
  }
  return { depth, providers }
}

// ------------------------------------------------------------- derivation rules

// Disclosed role semantics (the only code-level static surface):
//   tier:    model id ending in "flash" -> flash tier, otherwise full tier
//   worker:  name = <provider>-<model>, mode subagent
//   build:   name = build-<provider>-<model>, mode all, full permissions inherited
//   plan:    name = plan-<provider>-<model>, mode primary, read-only + context permissions
//   delegation:
//     build full  -> dev to flash worker, review/judgment/security to full worker
//     build flash -> ALL work to flash worker only
//   plan full  -> same-provider workers: flagship judgment + flash fast research
//     plan flash -> its exact flash worker
const tierOf = (model) => (model.endsWith("flash") ? "flash" : "full")
const workerName = (provider, model) => `${provider}-${model}`
const roleName = (role, provider, model) => `${role}-${provider}-${model}`

// Read-only bash allowlist for plan agents. Conservative: prefix patterns that
// cannot mutate state. Write-capable tools (sed, awk, redirect shells) are

# ---------------------------------------------------------------------------
# code_review round 3, WARN C: rotating an existing, valid client certificate
# must never strand the developer without ANY client credential. The
# pre-round-3 implementation truncated `key_out` via
# `_prepare_output_file(allow_overwrite=True)` before the first `openssl`
# call, then unlinked both `key_out` and `cert_out` in the `except CertsError`
# handler, so a failing `openssl` during a rotation destroyed the previously
# valid key and certificate a running instance still trusted, with nothing
# to replace them. `_issue_certificate` now writes into a temporary
# directory on the SAME filesystem as the final destination and commits both
# files with `os.replace` only after every `openssl` call has succeeded, the
# same commit-only-on-success guarantee `create_ca` gives its own material,
# mirroring the temporary-directory pattern `issue_server` already uses.
# ---------------------------------------------------------------------------


def test_issue_client_rotation_does_not_strand_developer_without_credential(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    certs = _import_certs()
    paths = certs.CertPaths(instance=f"issue-rotate-fail-{uuid.uuid4().hex[:8]}", root=tmp_path)
    certs.create_ca(paths)
    certs.issue_client(paths)
    original_key = paths.client_key.read_text(encoding="ascii")
    original_cert = paths.client_cert.read_text(encoding="ascii")

    failing_openssl = shutil.which("false")
    assert failing_openssl is not None, "the 'false' binary must be on PATH for this test"
    monkeypatch.setattr(certs, "OPENSSL_EXECUTABLE", failing_openssl)

    with pytest.raises(certs.CertsError, match="openssl"):
        certs.issue_client(paths)

    assert paths.client_key.read_text(encoding="ascii") == original_key
    assert paths.client_cert.read_text(encoding="ascii") == original_cert



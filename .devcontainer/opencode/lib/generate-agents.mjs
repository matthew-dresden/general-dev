const permission = {
  allow: (keys) => Object.fromEntries(keys.map((k) => [k, "allow"])),
}

function planPermission(task) {
  return {
    ...permission.allow(["read", "glob", "grep", "list", "webfetch", "websearch", "lsp", "skill", "question"]),
    edit: "deny",
    bash: { "*": "ask", ...Object.fromEntries(READ_ONLY_BASH.map((p) => [p, "allow"])) },
    task,
  }
}

// ---------------------------------------------------------------- YAML emitting

function yamlScalar(value) {
  return JSON.stringify(String(value))
}

function toYaml(value, indent = 0) {
  const pad = "  ".repeat(indent)
  if (value === null || typeof value !== "object") {
    return `${yamlScalar(value)}`
  }
  if (Array.isArray(value)) fail("arrays are not supported in agent frontmatter")
  const lines = []
  for (const [key, val] of Object.entries(value)) {
    if (val !== null && typeof val === "object") {
      lines.push(`${pad}${yamlScalar(key)}:`)
      lines.push(toYaml(val, indent + 1))
    } else {
      lines.push(`${pad}${yamlScalar(key)}: ${yamlScalar(val)}`)
    }
  }
  return lines.join("\n")
}

// ---------------------------------------------------------------- agent bodies

function concurrencyRule(provider, inputs) {
  const cap = inputs.concurrency[provider]
  if (cap !== undefined) {
    return `Parallel worker fan-out is capped at ${cap} concurrent for ${provider} (configured input); if docs indicate a lower limit, use the lower limit.`
  }
  return `Before spawning workers in parallel, determine the ${provider} concurrent-request limit for the model: look it up in provider documentation (webfetch) or ask the user; never assume. Cap fan-out to the discovered limit.`
}

function buildBody({ name, provider, model, tier, depth, flashWorker, fullWorker, inputs }) {
  const delegation =
    tier === "flash"
      ? `- ALL work - dev, review, judgment, security checks, and anything else - is ALWAYS and only delegated to the ${flashWorker} worker. You never delegate to any other agent.`
      : `- Dev execution: you do focused dev work directly. Parallelizable chunks (independent files, test scaffolding, mechanical refactors) are ALWAYS delegated to the ${flashWorker} worker.
- Review, judgment, design analysis, and security checks are ALWAYS delegated to the ${fullWorker} worker. The strict judge agents (code-reviewer, test-reviewer, doc-reviewer, security-reviewer, changes-manifest) return JSON verdicts you act on.`
  return `You are the ${name} session driver, running ${provider}/${model}. You manage development work and judgment work. Follow the engineering standards in AGENTS.md.

## Delegation contract
${delegation}
- Delegation discipline: every delegation gets a self-contained prompt (context, files, constraints, expected output). Verify delegated work before incorporating it.

## Fan-out discipline
- Nest agents as the work requires, up to ${depth} levels total (global subagent_depth).
- ${concurrencyRule(provider, inputs)}
- Same-provider rule: you may only delegate to agents on the ${provider} provider. The task permission list in your frontmatter enforces this fail-closed; do not route around it.

## Ownership
You own verification and final signoff: never mark work complete without verification (tests, lint, or explicit user confirmation). No fallback logic, no silent failures; every failure is fast, loud, and actionable.

Report back concisely: what you did, what you delegated, verification results.`
}

function planBody({ name, provider, model, depth, delegation, inputs }) {
  return `You are the ${name} planning agent, running ${provider}/${model}. You analyze code and produce plans; you cannot modify anything (file edits are denied). Follow the engineering standards in AGENTS.md.

## Interactivity mandate
Before producing any plan, surface every open decision to the user with the question tool: state your leading recommendation first, always include a free-text custom-answer option, and never proceed on an assumption you could have asked about.

## Capabilities
- Tool first: inspect the repo with the dedicated tools, not bash. Use read (its offset/limit arguments replace sed/awk line ranges), glob, grep, and list for anything inside the worktree; they run without approval and are the reason bash rarely needs to fire. Webfetch/websearch and LSP/skills also run without approval for external context.
- Bash is for what tools cannot do: git, gh, and cloud CLIs (az/aws/gcloud), and pipelines between the allowlisted text tools (jq, grep, tr, cut, sort, uniq). Read-only commands on that list run without approval; anything state-changing requires explicit user approval. Interpreters (python3, node -e) and awk are not allowlisted: restructure their work as jq or tool pipelines. Shell loops pass only when every parsed statement inside them is allowlisted; prefer single piped commands over loops.
- Delegate research and analysis to ${delegation}, as many in parallel as concurrency allows, nesting up to ${depth} levels.
- ${concurrencyRule(provider, inputs)}
- Verify delegated findings before folding them into the plan.

## Output
Concrete, actionable plans: file paths, exact changes, verification steps, and open questions resolved interactively.`
}

function workerBody({ name, provider, model, depth, inputs }) {
  return `You are the ${name} worker agent running ${provider}/${model}. You execute delegated chunks of work: development, review, judgment, security checks, and analysis. Follow the engineering standards in AGENTS.md.

- Do the delegated work with full tool access; fail fast, no fallback logic, no silent failures.
- You may delegate sub-chunks to same-provider workers (${provider}-glm-*) when it genuinely parallelizes the work, nesting up to ${depth} levels.
- ${concurrencyRule(provider, inputs)}
- Verify your own work (tests, lint) before reporting.

Report back concisely: what you did, what you delegated, verification results.`
}

// ---------------------------------------------------------------- agent set

function buildAgentSet(inputs, config) {
  const { depth, providers } = config
  const agents = []
  for (const provider of inputs.providers) {
    for (const model of providers[provider].modelIds) {
      const tier = tierOf(model)
      const flashWorker = workerName(provider, providers[provider].modelIds.find((m) => tierOf(m) === "flash") ?? fail(`${provider}: no flash-tier model is configured; the full-tier build profile requires one`))
      const fullWorker = workerName(provider, providers[provider].modelIds.find((m) => tierOf(m) === "full") ?? fail(`${provider}: no full-tier model is configured; the build profile requires one`))

      for (const role of inputs.roles) {
        const common = { role, provider, model, tier, file: `${roleName(role, provider, model)}.md`, name: roleName(role, provider, model) }
        if (role === "build") {
          agents.push({
            ...common,
            mode: "all",
            permission: { task: tier === "flash" ? { "*": "deny", [flashWorker]: "allow" } : { "*": "deny", [`${provider}-glm-*`]: "allow" } },
            description:
              tier === "flash"
                ? "Fast build driver: all work via the flash worker"
                : "Build driver: dev to flash, judgment to full worker",
            body: buildBody({ name: common.name, provider, model, tier, depth, flashWorker, fullWorker, inputs }),
          })
        } else {
          const worker = workerName(provider, model)
          // Flagship plan agents may delegate to BOTH same-provider workers
          // (flagship judgment + flash fast research); flash plan agents stay
          // locked to their exact flash worker.
          const task = tier === "flash" ? { "*": "deny", [worker]: "allow" } : { "*": "deny", [`${provider}-glm-*`]: "allow" }
          const delegation =
            tier === "flash"
              ? `the ${worker} worker (your exact provider and model)`
              : `the same-provider workers: ${fullWorker} (flagship judgment) and ${flashWorker} (fast research)`
          agents.push({
            ...common,
            mode: "primary",
            permission: planPermission(task),
            description: "Read-only planning agent; asks before assuming",
            body: planBody({ name: common.name, provider, model, depth, delegation, inputs }),
          })
        }
      }

      agents.push({
        role: "worker",
        provider,
        model,
        tier,
        file: `${workerName(provider, model)}.md`,
        name: workerName(provider, model),
        mode: "subagent",
        permission: { task: { "*": "deny", [`${provider}-glm-*`]: "allow" } },
        description:
          tier === "flash"
            ? "Fast worker: dev, review, judgment, security, analysis"
            : "Worker: dev, review, judgment, security",
        body: workerBody({ name: workerName(provider, model), provider, model, depth, inputs }),
      })
    }
  }
  return agents
}

function renderAgent(agent) {
  const frontmatter = {
    description: agent.description,
    mode: agent.mode,
    model: `${agent.provider}/${agent.model}`,
    permission: agent.permission,
  }
  return `---\n${toYaml(frontmatter)}\n---\n\n${MARKER}\n\n${agent.body}\n`
}

function renderManifest(agents, depth) {
  return `${JSON.stringify(
    {
      schema: MANIFEST_SCHEMA,
      generator: "lib/generate-agents.mjs",
      depth,
      agents: agents.map(({ name, role, provider, model, tier, mode, file }) => ({ name, role, provider, model, tier, mode, file })),
      policy: Object.fromEntries(
        [...new Set(agents.map((a) => a.provider))].map((provider) => [provider, [`${provider}-glm-*`]]),
      ),
      readOnlyBash: READ_ONLY_BASH,
    },
    null,
    2,
  )}\n`
}

// ------------------------------------------------------------------ IO modes

function writeAgentGuarded(path, content) {
  if (existsSync(path)) {
    const existing = readFileSync(path, "utf-8")
    if (!existing.includes(MARKER)) {
      fail(`refusing to overwrite non-generated file: ${path} (delete it or move it aside first)`)
    }
    if (existing === content) return false
  }
  writeFileSync(path, content)
  return true
}

function main() {
  const args = process.argv.slice(2)
  const modes = args.filter((a) => a.startsWith("--"))
  const unknown = modes.filter((m) => !["--dry-run", "--check"].includes(m))
  if (unknown.length > 0) fail(`unknown flags: ${unknown.join(", ")}`)
  if (modes.includes("--dry-run") && modes.includes("--check")) fail("--dry-run and --check are mutually exclusive")
  const dryRun = modes.includes("--dry-run")
  const check = modes.includes("--check")

  const inputs = readInputs()
  const config = readConfig(inputs)
  const agents = buildAgentSet(inputs, config)
  const manifest = renderManifest(agents, config.depth)

  if (dryRun) {
    console.log(`depth=${config.depth}`)
    for (const a of agents) console.log(`${a.mode.padEnd(8)} ${a.name.padEnd(30)} ${a.provider}/${a.model} (${a.tier})`)
    console.log("--- manifest ---")
    console.log(manifest)
    return
  }

  if (check) {
    const drift = []
    for (const a of agents) {
      const path = join(AGENT_DIR, a.file)
      const expected = renderAgent(a)
      if (!existsSync(path)) drift.push(`missing: ${a.file}`)
      else if (readFileSync(path, "utf-8") !== expected) drift.push(`stale: ${a.file}`)
    }
    if (!existsSync(MANIFEST_PATH)) drift.push("missing: lib/generated-agents.json")
    else if (readFileSync(MANIFEST_PATH, "utf-8") !== manifest) drift.push("stale: lib/generated-agents.json")
    const markerFiles = readdirSync(AGENT_DIR).filter((f) => f.endsWith(".md") && readFileSync(join(AGENT_DIR, f), "utf-8").includes(MARKER))
    const expectedFiles = new Set(agents.map((a) => a.file))
    for (const f of markerFiles) {
      if (!expectedFiles.has(f)) drift.push(`orphaned generated file: ${f} (no longer derived; delete it)`)
    }
    if (drift.length > 0) {
      console.error(`OUT OF SYNC (${drift.length}):\n${drift.map((d) => `  - ${d}`).join("\n")}\nRun: /generate-agents`)
      process.exit(1)
    }
    console.log(`IN SYNC (${agents.length} agents + manifest)`)
    return
  }

  const written = []
  for (const a of agents) {
    if (writeAgentGuarded(join(AGENT_DIR, a.file), renderAgent(a))) written.push(a.file)
  }
  // The manifest is generator-owned by path: only this script writes it, and its
  // JSON body cannot carry the agent marker, so the marker guard does not apply.
  if (!existsSync(MANIFEST_PATH) || readFileSync(MANIFEST_PATH, "utf-8") !== manifest) {
    writeFileSync(MANIFEST_PATH, manifest)
    written.push("lib/generated-agents.json")
  }
  console.log(`Wrote ${written.length} file(s):`)
  for (const f of written) console.log(`  ${f}`)
  console.log(`Verified set: ${agents.length} agents (restart opencode to load changes)`)
}

main()